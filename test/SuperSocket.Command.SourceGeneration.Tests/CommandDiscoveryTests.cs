    [Fact]
    public void Generator_WrapsCommandsWhosePackageInterfaceIsImplementedByRegistryPackage()
    {
        var result = GeneratorTestHarness.Run("""
            using System.Threading;
            using System.Threading.Tasks;
            using SuperSocket.Command;
            using SuperSocket.Server.Abstractions.Session;

            namespace Demo;

            public interface IFakePkg
            {
            }

            public sealed class FakePkg : IFakePkg
            {
            }

            public sealed class OtherPkg
            {
            }

            [Command("ASYNC")]
            public class AsyncInterfaceCmd : IAsyncCommand<IAppSession, IFakePkg>
            {
                public ValueTask ExecuteAsync(IAppSession session, IFakePkg package, CancellationToken cancellationToken)
                    => default;
            }

            [Command("SYNC")]
            public class SyncInterfaceCmd : ICommand<IAppSession, IFakePkg>
            {
                public void Execute(IAppSession session, IFakePkg package)
                {
                }
            }

            [Command("EXACT")]
            public class ExactCmd : ICommand<IAppSession, FakePkg>
            {
                public void Execute(IAppSession session, FakePkg package)
                {
                }
            }

            [Command("MISMATCH")]
            public class MismatchCmd : ICommand<IAppSession, OtherPkg>
            {
                public void Execute(IAppSession session, OtherPkg package)
                {
                }
            }

            [CommandRegistry]
            public partial class Reg : IGeneratedCommandRegistry<string, FakePkg>
            {
            }
            """);

        string generatedSource = result.GeneratedTrees
            .Single(static tree => tree.FilePath.EndsWith("Demo.Reg.Registry.g.cs", StringComparison.Ordinal))
            .GetText(TestContext.Current.CancellationToken)
            .ToString();

        Assert.Contains("global::SuperSocket.Command.AsyncCommandWrap<global::SuperSocket.Server.Abstractions.Session.IAppSession, global::Demo.FakePkg, global::Demo.IFakePkg, global::Demo.AsyncInterfaceCmd>", generatedSource, StringComparison.Ordinal);
        Assert.Contains("global::SuperSocket.Command.CommandWrap<global::SuperSocket.Server.Abstractions.Session.IAppSession, global::Demo.FakePkg, global::Demo.IFakePkg, global::Demo.SyncInterfaceCmd>", generatedSource, StringComparison.Ordinal);
        Assert.Contains("global::Microsoft.Extensions.DependencyInjection.ActivatorUtilities.CreateInstance<global::Demo.AsyncInterfaceCmd>(sp)", generatedSource, StringComparison.Ordinal);
        Assert.Contains("global::Microsoft.Extensions.DependencyInjection.ActivatorUtilities.CreateInstance<global::Demo.SyncInterfaceCmd>(sp)", generatedSource, StringComparison.Ordinal);
        Assert.DoesNotContain("new global::SuperSocket.Command.AsyncCommandWrap<global::SuperSocket.Server.Abstractions.Session.IAppSession, global::Demo.FakePkg, global::Demo.IFakePkg, global::Demo.AsyncInterfaceCmd>(sp)", generatedSource, StringComparison.Ordinal);
        Assert.DoesNotContain("new global::SuperSocket.Command.CommandWrap<global::SuperSocket.Server.Abstractions.Session.IAppSession, global::Demo.FakePkg, global::Demo.IFakePkg, global::Demo.SyncInterfaceCmd>(sp)", generatedSource, StringComparison.Ordinal);
        Assert.Contains("global::Microsoft.Extensions.DependencyInjection.ActivatorUtilities.CreateInstance<global::Demo.ExactCmd>(sp),", generatedSource, StringComparison.Ordinal);
        Assert.DoesNotContain("CommandWrap<global::SuperSocket.Server.Abstractions.Session.IAppSession, global::Demo.FakePkg, global::Demo.FakePkg, global::Demo.ExactCmd>", generatedSource, StringComparison.Ordinal);
        Assert.DoesNotContain("global::Demo.MismatchCmd", generatedSource, StringComparison.Ordinal);
    }


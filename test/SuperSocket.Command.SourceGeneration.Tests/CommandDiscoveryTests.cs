    [Fact]
    public void Generator_EmitsDiscoveredCommandsForMatchingRegistryPackage()
    {
        var result = GeneratorTestHarness.Run("""
            using System;
            using System.Threading;
            using System.Threading.Tasks;
            using SuperSocket.Command;
            using SuperSocket.Server.Abstractions.Session;

            namespace Demo;

            public sealed class FakePkg
            {
            }

            [Command("ADD")]
            public class AddCmd : IAsyncCommand<IAppSession, FakePkg>
            {
                public ValueTask ExecuteAsync(IAppSession session, FakePkg package, CancellationToken cancellationToken)
                    => default;
            }

            [Command("ONE", "1")]
            public class OneCmd : ICommand<IAppSession, FakePkg>
            {
                public void Execute(IAppSession session, FakePkg package)
                {
                }
            }

            [CommandRegistry]
            public partial class Reg : IGeneratedCommandRegistry<string, FakePkg>
            {
            }
            """);

        string generatedSource = result.GeneratedTrees
            .Single(static tree => tree.FilePath.EndsWith("Demo.Reg.Registry.g.cs", StringComparison.Ordinal))
            .GetText(TestContext.Current.CancellationToken)
            .ToString();

        Assert.Contains("// <auto-generated/>", generatedSource, StringComparison.Ordinal);
        Assert.Contains("public partial class Reg", generatedSource, StringComparison.Ordinal);
        Assert.Contains("GetRegistrations()", generatedSource, StringComparison.Ordinal);
        Assert.Contains("yield return new global::SuperSocket.Command.CommandRegistration<", generatedSource, StringComparison.Ordinal);
        Assert.Contains("global::SuperSocket.Command.TypedCommandSet<", generatedSource, StringComparison.Ordinal);
        Assert.Contains("global::Microsoft.Extensions.DependencyInjection.ActivatorUtilities.CreateInstance<global::Demo.AddCmd>(sp)", generatedSource, StringComparison.Ordinal);
        Assert.Contains("global::System.Array.Empty<global::SuperSocket.Command.ICommandFilter>()", generatedSource, StringComparison.Ordinal);
        Assert.Contains("Demo.AddCmd", generatedSource, StringComparison.Ordinal);
        Assert.Contains("\"ADD\"", generatedSource, StringComparison.Ordinal);
        Assert.Contains("Demo.OneCmd", generatedSource, StringComparison.Ordinal);
        Assert.Contains("\"1\"", generatedSource, StringComparison.Ordinal);
    }

